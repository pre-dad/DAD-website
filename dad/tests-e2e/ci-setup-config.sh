#!/usr/bin/env bash
#
# ci-setup-config.sh: write a throwaway dad/api/config.php for CI and local runs:
# a fresh temp database, no SMTP, example.com quiet, the 127.0.0.1:8080 origin
# allowed, and the setup key the admin e2e spec uses. Run from dad/.
#
#   bash tests-e2e/ci-setup-config.sh --ci       # write it (alias: --force)
#   bash tests-e2e/ci-setup-config.sh --restore  # put back a real config it backed up
#
# Without --ci it refuses to replace an existing config.php. With it, an existing
# config.php is first copied to config.php.ci-backup (never over an older backup,
# which may hold the only real copy).

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DAD_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
CONFIG="$DAD_DIR/api/config.php"
BACKUP="$CONFIG.ci-backup"

FORCE=0
RESTORE=0
for arg in "$@"; do
  case "$arg" in
    --ci|--force) FORCE=1 ;;
    --restore) RESTORE=1 ;;
    *) echo "ci-setup-config.sh: unknown arg '$arg'" >&2; exit 2 ;;
  esac
done

if [[ "$RESTORE" -eq 1 ]]; then
  if [[ -f "$BACKUP" ]]; then
    mv -f "$BACKUP" "$CONFIG"
    echo "ci-setup-config.sh: restored real config.php from backup"
  else
    echo "ci-setup-config.sh: no backup to restore (config.php.ci-backup absent)." >&2
    echo "Nothing done. (In CI there is no real config to restore — this is fine.)" >&2
  fi
  exit 0
fi

if [[ -f "$CONFIG" && "$FORCE" -ne 1 ]]; then
  echo "ci-setup-config.sh: $CONFIG already exists." >&2
  echo "Refusing to overwrite a real config without --ci/--force." >&2
  echo "In CI there is no real config.php so pass --ci there." >&2
  exit 1
fi

if [[ -f "$CONFIG" && "$FORCE" -eq 1 ]]; then
  if [[ ! -f "$BACKUP" ]]; then
    cp -p "$CONFIG" "$BACKUP"
    echo "ci-setup-config.sh: backed up existing config.php -> config.php.ci-backup (run --restore to put it back)"
  else
    echo "ci-setup-config.sh: keeping existing config.php.ci-backup (not overwriting the saved real config)"
  fi
fi

# The admin e2e spec opens /api/admin/?setup=ci-setup-key; this is its hash.
SETUP_KEY_SHA256="$(printf '%s' 'ci-setup-key' | php -r 'echo hash("sha256", stream_get_contents(STDIN));')"

DATA_DIR="$(mktemp -d "${TMPDIR:-/tmp}/dad-ci-data-XXXXXXXX")"
echo "ci-setup-config.sh: SITE_DATA_DIR = $DATA_DIR"

cat > "$CONFIG" <<PHP
<?php
// THROWAWAY CI / local-E2E config. Generated by tests-e2e/ci-setup-config.sh.
// Not a secret, never committed (gitignored by **/config.php). Points at a temp
// data dir; all SMTP blank; example.com quiet so no mail is sent.
defined('SITE_API') || exit;

const SITE_TZ   = 'America/New_York';
const SITE_BASE = 'http://127.0.0.1:8080';

const SITE_DATA_DIR = '$DATA_DIR';

const SITE_SETUP_KEY_SHA256 = '$SETUP_KEY_SHA256';

const SITE_NOTIFY_TO        = 'team@example.com';
const SITE_NOTIFY_TYPES     = ['founding', 'updates', 'support', 'volunteer', 'contact', 'partner'];
const SITE_NOTIFY_FROM      = 'no-reply@example.com';
const SITE_NOTIFY_FROM_NAME = 'DAD CI';

const SITE_MAIL_FROM      = 'hello@example.com';
const SITE_MAIL_FROM_NAME = 'DAD';
const SITE_MAIL_REPLY_TO  = 'hello@example.com';

const SITE_RATE_LIMIT_PER_HOUR        = 1000;
const SITE_MIN_FILL_MS                = 0;
const SITE_MAX_CONFIRMATIONS_PER_HOUR = 200;
const SITE_QUIET_DOMAINS              = ['example.com'];

const SITE_ALLOWED_ORIGINS = ['http://127.0.0.1:8080'];

const SITE_SMTP_HOST   = '';
const SITE_SMTP_PORT   = 587;
const SITE_SMTP_USER   = '';
const SITE_SMTP_PASS   = '';
const SITE_SMTP_SECURE = 'tls';
PHP

echo "ci-setup-config.sh: wrote $CONFIG"
