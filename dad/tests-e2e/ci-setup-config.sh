#!/usr/bin/env bash
#
# ci-setup-config.sh — write a THROWAWAY dad/api/config.php for CI / local E2E.
#
# The real config.php is gitignored and absent in CI. This writes a disposable
# one that points SITE_DATA_DIR at a fresh temp dir, leaves all SMTP blank (so
# mail() is never dialed out — and example.com is a quiet domain, so no mail is
# attempted at all), and allows the 127.0.0.1:8080 origin the E2E server uses.
#
# It NEVER reads or copies the real config.php or the real data dir.
#
# Usage:
#   bash tests-e2e/ci-setup-config.sh --ci       # run from dad/
#   bash tests-e2e/ci-setup-config.sh --force    # alias for --ci
#
# LOCAL-DEV GUARD: if dad/api/config.php already exists and no --ci/--force flag
# is passed, this refuses (so a developer's real config is never clobbered). With
# the flag, an existing config.php is backed up to config.php.ci-backup and
# restored would be manual — the flag is an explicit "yes, overwrite" for CI.

set -euo pipefail

# Resolve dad/ relative to this script (tests-e2e/ lives inside dad/).
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DAD_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
CONFIG="$DAD_DIR/api/config.php"

FORCE=0
for arg in "$@"; do
  case "$arg" in
    --ci|--force) FORCE=1 ;;
    *) echo "ci-setup-config.sh: unknown arg '$arg'" >&2; exit 2 ;;
  esac
done

if [[ -f "$CONFIG" && "$FORCE" -ne 1 ]]; then
  echo "ci-setup-config.sh: $CONFIG already exists." >&2
  echo "Refusing to overwrite a real config without --ci/--force." >&2
  echo "In CI there is no real config.php so pass --ci there." >&2
  exit 1
fi

if [[ -f "$CONFIG" && "$FORCE" -eq 1 ]]; then
  cp -p "$CONFIG" "$CONFIG.ci-backup"
  echo "ci-setup-config.sh: backed up existing config.php -> config.php.ci-backup"
fi

# Fresh, unguessable temp data dir OUTSIDE the repo tree.
DATA_DIR="$(mktemp -d "${TMPDIR:-/tmp}/dad-ci-data-XXXXXXXX")"
echo "ci-setup-config.sh: SITE_DATA_DIR = $DATA_DIR"

cat > "$CONFIG" <<PHP
<?php
// THROWAWAY CI / local-E2E config. Generated by tests-e2e/ci-setup-config.sh.
// Not a secret, never committed (gitignored by **/config.php). Points at a temp
// data dir; all SMTP blank; example.com quiet so no mail is sent.
defined('SITE_API') || exit;

const SITE_TZ   = 'America/New_York';
const SITE_BASE = 'http://127.0.0.1:8080';

const SITE_DATA_DIR = '$DATA_DIR';

const SITE_SETUP_KEY_SHA256 = '';

const SITE_NOTIFY_TO        = 'team@example.com';
const SITE_NOTIFY_TYPES     = ['founding', 'updates', 'support', 'volunteer', 'contact', 'partner'];
const SITE_NOTIFY_FROM      = 'no-reply@example.com';
const SITE_NOTIFY_FROM_NAME = 'DAD CI';

const SITE_MAIL_FROM      = 'hello@example.com';
const SITE_MAIL_FROM_NAME = 'DAD';
const SITE_MAIL_REPLY_TO  = 'hello@example.com';

const SITE_RATE_LIMIT_PER_HOUR        = 1000;
const SITE_MIN_FILL_MS                = 0;
const SITE_MAX_CONFIRMATIONS_PER_HOUR = 200;
const SITE_QUIET_DOMAINS              = ['example.com'];

const SITE_ALLOWED_ORIGINS = ['http://127.0.0.1:8080'];

const SITE_SMTP_HOST   = '';
const SITE_SMTP_PORT   = 587;
const SITE_SMTP_USER   = '';
const SITE_SMTP_PASS   = '';
const SITE_SMTP_SECURE = 'tls';
PHP

echo "ci-setup-config.sh: wrote $CONFIG"
